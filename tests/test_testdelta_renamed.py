class TestUnittestUnaffected(_Files):
    """Test 5: unittest ids are never grouped, even with brackets."""

    def test_unittest_bracket_names_stay_removed_and_added(self):
        before = fx.ut_simple([("test_x[a]", "pass"), ("test_y", "pass")])
        after = fx.ut_simple([("test_x[b]", "pass"), ("test_y", "pass")])
        paths = self.files(before, after, ".txt")
        code, doc = self.json_report(paths)
        self.assertEqual(code, EXIT_REGRESSIONS)
        self.assertEqual(doc["input_format"], "unittest")
        self.assertEqual(doc["renamed_params"], [])
        self.assertEqual(ids(doc, "removed"), ["pkg.mod.Class.test_x[a]"])
        self.assertEqual(ids(doc, "added"), ["pkg.mod.Class.test_x[b]"])
        for fmt in ("text", "md", "html"):
            with self.subTest(fmt=fmt):
                default = self.report(paths, fmt)
                strict = self.report(paths, fmt, "--strict-ids")
                self.assertEqual(default, strict)


class TestFormats(_Files):
    """Test 6: JSON renamed_params and the warning and section in md/html."""

    def test_json_shape(self):
        code, doc = self.json_report(self.scenario("real"))
        self.assertEqual(code, EXIT_OK)
        self.assertEqual(doc["schema"], "testdelta/1")
        self.assertEqual(list(doc)[-1], "renamed_params")
        entry = doc["renamed_params"][0]
        self.assertEqual(list(entry), ["base_id", "count", "status", "examples"])
        self.assertTrue(entry["examples"])
        for example in entry["examples"]:
            self.assertEqual(list(example), ["before", "after"])
        self.assertIn(WARNING, doc["warnings"])

    def test_json_key_present_when_empty(self):
        paths = self.files(fx.junit_simple([("t1", "pass")]),
                           fx.junit_simple([("t1", "pass")]))
        code, doc = self.json_report(paths)
        self.assertEqual(code, EXIT_OK)
        self.assertEqual(doc["renamed_params"], [])

    def test_md_warning_and_section(self):
        code, out = self.report(self.scenario("real"), "md")
        self.assertEqual(code, EXIT_OK)
        self.assertIn(f"- {WARNING}\n", out)
        self.assertIn("## Renamed parametrized tests (6)", out)
        first = (f"{fx.RENAME_CLASS}::{fx.stamped(fx.STAMP_BEFORE, 1)}"
                 .replace("[", "\\[").replace("]", "\\]"))
        self.assertIn(first, out)
        self.assertLess(out.index("## Other status changes"),
                        out.index("## Renamed parametrized tests"))

    def test_html_warning_and_section(self):
        code, out = self.report(self.scenario("real"), "html")
        self.assertEqual(code, EXIT_OK)
        self.assertIn(WARNING, out)
        self.assertIn("<h2>Renamed parametrized tests (6)</h2>", out)

    def test_no_section_without_renames(self):
        paths = self.files(fx.junit_simple([("t1", "pass")]),
                           fx.junit_simple([("t1", "pass")]))
        for fmt in ("text", "md", "html"):
            with self.subTest(fmt=fmt):
                self.assertEqual(self.report(paths, fmt),
                                 self.report(paths, fmt, "--strict-ids"))

    def test_renamed_ids_redacted_and_escaped(self):
        token = ss.GHP + "A1b2C3d4E5F6g7H8i9J0k1L2m3N4o5P6q7R8"
        before = fx.junit_simple([(f"test_tok[{token}|old\u202e]", "pass")])
        after = fx.junit_simple([(f"test_tok[{token}|new\u202e]", "pass")])
        paths = self.files(before, after)
        for fmt in ("text", "md", "html", "json"):
            with self.subTest(fmt=fmt):
                code, out = self.report(paths, fmt)
                self.assertEqual(code, EXIT_OK)
                self.assertIn("test_tok", out)
                self.assertNotIn(token, out)
                self.assertNotIn("\u202e", out)


class TestTwoBases(_Files):
    """Test 7: two base ids changing at once are handled independently."""

    def test_two_bases_independent(self):
        code, doc = self.json_report(self.scenario("two_bases"))
        self.assertEqual(code, EXIT_REGRESSIONS)
        where = fx.RENAME_CLASS
        self.assertEqual([(e["base_id"], e["count"]) for e in doc["renamed_params"]],
                         [(f"{where}::test_alpha", 2)])
        self.assertEqual(ids(doc, "removed"), [f"{where}::test_beta[old0]",
                                               f"{where}::test_beta[old1]"])
        self.assertEqual(ids(doc, "added"), [f"{where}::test_beta[new0]"])
        self.assertEqual(doc["summary"], {"regressions": 2, "improvements": 1})


