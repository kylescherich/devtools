BASE = f"{fx.RENAME_CLASS}::{fx.RENAME_BASE}"
WARNING = ("6 parametrized tests renamed (ids not stable: "
           f"{BASE}) -- fix the ids")


def run(argv):
    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        code = main([str(a) for a in argv])
    return code, out.getvalue(), err.getvalue()


def sha256(text):
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def ids(doc, name):
    return [item["id"] for item in doc[name]]


class _Files(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.dir = self._tmp.name

    def tearDown(self):
        self._tmp.cleanup()

    def files(self, before, after, suffix=".xml"):
        return (fx.write(self.dir, "before" + suffix, before),
                fx.write(self.dir, "after" + suffix, after))

    def scenario(self, name):
        return self.files(*fx.RENAME_SCENARIOS[name]())

    def report(self, paths, fmt="text", *extra):
        code, out, err = run([*paths, "--format", fmt, *extra])
        self.assertTrue(out, err)
        return code, out

    def json_report(self, paths, *extra):
        code, out = self.report(paths, "json", *extra)
        return code, json.loads(out)


class TestBaseId(unittest.TestCase):
    def test_base_id(self):
        cases = {
            "pkg.mod.Class::test_x[a]": "pkg.mod.Class::test_x",
            "pkg.mod.Class::test_x[[1, 2]]": "pkg.mod.Class::test_x",
            "pkg.mod.Class::test_x[a]b]": "pkg.mod.Class::test_x",
            "tests/t.py::test_x[2026-10-21 05:54:54.841690]": "tests/t.py::test_x",
            "test_x[a]": "test_x",
            "pkg.mod.Class::test_x": None,
            "pkg[a].Class::test_x": None,
            "pkg[a]::test_x[b]": "pkg[a]::test_x",
            "pkg.mod.Class::test_x[a]tail": None,
            "pkg.mod.Class::[a]": None,
        }
        for test_id, expected in cases.items():
            with self.subTest(test_id=test_id):
                self.assertEqual(cmp.base_id(test_id), expected)


class TestRealShape(_Files):
    """Test 1: the BRIEF-HARNESS-037 shape, 6 stamped ids, all passing."""

    def test_six_renamed_none_removed_exit_0(self):
        paths = self.scenario("real")
        code, doc = self.json_report(paths)
        self.assertEqual(code, EXIT_OK)
        self.assertEqual(doc["removed"], [])
        self.assertEqual(doc["added"], [])
        self.assertEqual(doc["added_failing"], [])
        self.assertEqual(doc["summary"], {"regressions": 0, "improvements": 0})
        self.assertEqual(len(doc["renamed_params"]), 1)
        entry = doc["renamed_params"][0]
        self.assertEqual(entry["base_id"], BASE)
        self.assertEqual(entry["count"], 6)
        self.assertEqual(entry["status"], "pass")
        self.assertEqual(entry["examples"], [
            {"before": f"{fx.RENAME_CLASS}::{fx.stamped(fx.STAMP_BEFORE, k)}",
             "after": f"{fx.RENAME_CLASS}::{fx.stamped(fx.STAMP_AFTER, k)}"}
            for k in (1, 2, 3)])

    def test_text_says_no_regressions(self):
        code, out = self.report(self.scenario("real"))
        self.assertEqual(code, EXIT_OK)
        self.assertIn("RESULT no regressions", out)
        self.assertIn("REMOVED (0)", out)
        self.assertIn("RENAMED PARAMETRIZED TESTS (6)", out)
        self.assertIn(f"  ! {WARNING}", out)
        self.assertNotIn("WARNINGS none", out)


class TestStatusDifference(_Files):
    """Test 2: one after-case fails, so the whole group stays as today."""

    def test_one_failing_case_keeps_removed_and_added(self):
        paths = self.scenario("one_fails")
        code, doc = self.json_report(paths)
        self.assertEqual(code, EXIT_REGRESSIONS)
        self.assertEqual(doc["renamed_params"], [])
        self.assertEqual(len(doc["removed"]), 6)
        self.assertEqual(len(doc["added"]) + len(doc["added_failing"]), 6)
        self.assertEqual(ids(doc, "added_failing"),
                         [f"{fx.RENAME_CLASS}::{fx.stamped(fx.STAMP_AFTER, 3)}"])

    def test_reported_exactly_as_today(self):
        paths = self.scenario("one_fails")
        for fmt in ("text", "md", "html"):
            with self.subTest(fmt=fmt):
                code, out = self.report(paths, fmt)
                self.assertEqual((code, sha256(out)), GOLDEN[("one_fails", fmt, False)])
        code, doc = self.json_report(paths)
        _, strict = self.json_report(paths, "--strict-ids")
        self.assertEqual(doc.pop("renamed_params"), [])
        self.assertEqual(doc, strict)

    def test_all_failing_group_renamed_with_status_shown(self):
        paths = self.files(fx.junit_simple([("test_f[b0]", "fail"), ("test_f[b1]", "fail")]),
                           fx.junit_simple([("test_f[a0]", "fail"), ("test_f[a1]", "fail")]))
        code, doc = self.json_report(paths)
        self.assertEqual([(e["base_id"], e["count"], e["status"])
                          for e in doc["renamed_params"]],
                         [("pkg.mod.Class::test_f", 2, "fail")])
        self.assertEqual(doc["removed"], [])
        self.assertEqual(doc["added_failing"], [])
        self.assertEqual(code, EXIT_OK)
        _, out = self.report(paths, "text")
        self.assertIn("2 x fail  pkg.mod.Class::test_f", out)


